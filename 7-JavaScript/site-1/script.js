// O print() agora é console.log()
console.log("Hello World");

// const para valores que NÃO mudam (Constantes)
const linguagem = "JavaScript";
const turma = 202;

// let para valores que PODEM mudar
let estado = "Iniciante";

console.log("Linguagem selecionada: ", linguagem);
console.log("Turma: ", turma);
console.log("Status atual: ", estado);

// Mudando o valor da variável 'let' (não usamos a palavra 'let' de novo)
estado = "Desenvolvedor Web em Treinamento";
console.log("Novo status: ", estado);